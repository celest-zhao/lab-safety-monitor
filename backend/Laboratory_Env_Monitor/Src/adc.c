/*******************************************************************************
* 名    称：adc1_getvalue
* 功    能：获取ADC转化后的值
* 参数说明：*Voltage：获取的电压值
* 返 回 值：无
* 说    明：无
* 调用方法：外部调用
*******************************************************************************/
void adc1_getvalue(float * Voltage)
{
    uint32_t AD_Value = 0;
      HAL_ADC_Start(&hadc1);									// 开启ADC检测
    if(HAL_ADC_PollForConversion(&hadc1, 100) == HAL_OK)        // 等待转换完成
    {
        AD_Value = HAL_ADC_GetValue(&hadc1)+0x1c;
        *Voltage = (float)AD_Value*3.28f/4095;    
    }
}

